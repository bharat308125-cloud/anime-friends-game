-- Run this in Supabase SQL Editor for the initial prototype.
-- IMPORTANT: This starter is designed for a public-by-link game. Anyone with a game link
-- can read that game's friends' names/photo paths and submit a match. Do not upload photos
-- without permission. The public bucket allows photo URLs to be viewed by anyone who has them.

create extension if not exists pgcrypto;

create table if not exists public.games (
  id text primary key,
  owner_name text not null,
  theme text not null default 'one_piece',
  friends jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  game_id text not null references public.games(id) on delete cascade,
  participant_name text not null,
  matches jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.games enable row level security;
alter table public.submissions enable row level security;

-- Prototype policies: public can read games and submit matches, but cannot update/delete games.
-- For production, consider an Edge Function or server-side validation to prevent spam.
create policy "Anyone can read games by link"
on public.games for select to anon, authenticated using (true);

create policy "Anyone can create a game"
on public.games for insert to anon, authenticated with check (true);

create policy "Anyone can submit matches"
on public.submissions for insert to anon, authenticated with check (true);

create policy "Anyone can read submissions"
on public.submissions for select to anon, authenticated using (true);

-- Create a PUBLIC storage bucket named friend-photos in Storage UI.
-- Then add this policy so the app can upload files from the browser.
create policy "Anyone can upload friend photos"
on storage.objects for insert to anon, authenticated
with check (bucket_id = 'friend-photos');

